#!/usr/bin/env python3
"""
gen_isa_test.py - writes testbench/programs/isa_test.s, a self-checking program
that tests every RV32I instruction the ProtocolX core supports.

How a test works (in assembly):
    li   x31, <test number>          # remember which test is running
    li   x5, <a>  ;  li x6, <b>      # operands
    <op> x7, x5, x6                  # instruction under test
    li   x8, <expected>              # answer computed HERE, in Python
    bne  x7, x8, fail                # wrong -> jump to fail
At "fail" the program writes the failing test number to TOHOST (data-RAM address 0xFFC);
if every test passes it writes 1. The testbench prints the result.

Python computes every expected value with a tiny reference model below, so we
never hand-calculate (and never mistype) hundreds of answers.
"""
import os

M32 = 0xFFFFFFFF


def s32(x):            # interpret as signed 32-bit
    x &= M32
    return x - (1 << 32) if x & 0x80000000 else x


def u32(x):
    return x & M32


REF = {
    "add":  lambda a, b: u32(a + b),
    "sub":  lambda a, b: u32(a - b),
    "sll":  lambda a, b: u32(a << (b & 31)),
    "slt":  lambda a, b: int(s32(a) < s32(b)),
    "sltu": lambda a, b: int(u32(a) < u32(b)),
    "xor":  lambda a, b: u32(a ^ b),
    "srl":  lambda a, b: u32(a) >> (b & 31),
    "sra":  lambda a, b: u32(s32(a) >> (b & 31)),
    "or":   lambda a, b: u32(a | b),
    "and":  lambda a, b: u32(a & b),
}
I_OF = {"addi": "add", "slti": "slt", "sltiu": "sltu", "xori": "xor", "ori": "or", "andi": "and",
        "slli": "sll", "srli": "srl", "srai": "sra"}
BR = {"beq": lambda a, b: a == b, "bne": lambda a, b: a != b,
      "blt": lambda a, b: s32(a) < s32(b), "bge": lambda a, b: s32(a) >= s32(b),
      "bltu": lambda a, b: u32(a) < u32(b), "bgeu": lambda a, b: u32(a) >= u32(b)}

PAIRS = [(0, 0), (1, 1), (0xFFFFFFFF, 1), (0x7FFFFFFF, 0xFFFFFFFF), (0x80000000, 0xFFFFFFFF),
         (0x12345678, 0x0000FFFF), (0xFFFFFF85, 7)]
IMMS = [(0, 0), (5, -1), (0xFFFFFFF0, 15), (0x7FFFFFFF, 2047), (0x80000000, -2048)]
SHAMTS = [(0x80000001, 0), (0x80000001, 1), (0xF0F0F0F0, 4), (0xFFFFFFFF, 31)]

out = []
n = [1]


def emit(*lines):
    out.extend(lines)


def check(reg, expected):
    """Compare reg with expected value; jump to fail on mismatch."""
    emit(f"    li   x8, {u32(expected):#x}", f"    bne  {reg}, x8, fail")


def new_test(comment):
    n[0] += 1
    emit(f"# test {n[0]}: {comment}", f"    li   x31, {n[0]}")


emit("# Generated by scripts/gen_isa_test.py - do not edit by hand.",
     "# Self-checking RV32I test. Writes 1 to TOHOST on pass, failing test number on fail.",
     "    li   x30, 0xFFC               # x30 = TOHOST address (last RAM word)")

# ---- register-register ALU
for op in REF:
    for a, b in PAIRS:
        new_test(f"{op} {a:#x}, {b:#x}")
        emit(f"    li   x5, {a:#x}", f"    li   x6, {b:#x}", f"    {op:6} x7, x5, x6")
        check("x7", REF[op](a, b))

# ---- register-immediate ALU
for op, base in I_OF.items():
    cases = SHAMTS if op in ("slli", "srli", "srai") else IMMS
    for a, imm in cases:
        new_test(f"{op} {a:#x}, {imm}")
        emit(f"    li   x5, {a:#x}", f"    {op:6} x7, x5, {imm}")
        check("x7", REF[base](a, u32(imm)))

# ---- forwarding: the result is used by the very next instruction (no NOPs)
new_test("back-to-back dependency chain (forwarding)")
emit("    li   x5, 3", "    add  x6, x5, x5", "    add  x7, x6, x5", "    add  x7, x7, x6", "    sub  x7, x7, x5")
check("x7", ((3 + 3 + 3) + 6) - 3)

# ---- LUI / AUIPC
new_test("lui")
emit("    lui  x7, 0xABCDE")
check("x7", 0xABCDE000)
new_test("auipc (difference of two auipc = distance in bytes)")
emit("    auipc x5, 0", "    auipc x6, 1", "    sub  x7, x6, x5")
check("x7", 0x1004)

# ---- loads and stores (word access, data RAM at 0x100)
emit("    li   x9, 0x100                # x9 = data address")
new_test("sw / lw")
emit("    li   x5, 0x8899AABB", "    sw   x5, 0(x9)", "    lw   x7, 0(x9)")
check("x7", 0x8899AABB)
new_test("load-use: value loaded and used immediately (1-cycle stall)")
emit("    lw   x5, 0(x9)", "    addi x7, x5, 1")
check("x7", 0x8899AABC)
new_test("store data forwarded from the previous instruction")
emit("    addi x5, x0, 77", "    sw   x5, 4(x9)", "    lw   x7, 4(x9)")
check("x7", 77)

# ---- branches: x7 = 0 if the branch was taken (skipped the li), 1 if not taken
for op, cond in BR.items():
    for a, b in [(5, 5), (5, 6), (0xFFFFFFFF, 1), (1, 0xFFFFFFFF)]:
        new_test(f"{op} {a:#x}, {b:#x}")
        lab = f"br{n[0]}"
        emit(f"    li   x5, {a:#x}", f"    li   x6, {b:#x}", "    li   x7, 0",
             f"    {op:5} x5, x6, {lab}", "    li   x7, 1", f"{lab}:")
        check("x7", 0 if cond(a, b) else 1)

# ---- backward branch loop (taken many times, then falls through)
new_test("backward loop with bne, 10 iterations")
emit("    li   x5, 10", "    li   x7, 0", f"loop{n[0]}:", "    addi x7, x7, 2",
     "    addi x5, x5, -1", f"    bne  x5, x0, loop{n[0]}")
check("x7", 20)

# ---- JAL / JALR
new_test("jal: link register = address after jal")
emit("    auipc x6, 0", f"    jal  x5, j{n[0]}", "    li   x31, 1000", f"j{n[0]}:", "    sub  x7, x5, x6")
check("x7", 8)
new_test("jalr: jump to rs1+imm, link = next address")
emit("    auipc x6, 0", "    addi x6, x6, 16", "    jalr x5, 0(x6)", "    li   x31, 1000",
     "    sub  x7, x5, x6")      # lands here (auipc + 16)
check("x7", 12 - 16)

new_test("writes to x0 are ignored")
emit("    li   x0, 55", "    add  x7, x0, x0")
check("x7", 0)

emit("pass:", "    li   x5, 1", "    sw   x5, 0(x30)", "done:", "    j    done",
     "fail:", "    sw   x31, 0(x30)", "    j    done")

here = os.path.dirname(os.path.abspath(__file__))
path = os.path.join(here, "..", "testbench", "programs", "isa_test.s")
open(path, "w").write("\n".join(out) + "\n")
print(f"wrote {os.path.normpath(path)}: {n[0] - 1} tests")
